def нормализовать(text):
    for ch in '”“"?!()':
        text = text.replace(ch, '')
    for ch in '.,\t':
        text = text.replace(ch, ' ')
    return text.replace('\n', '').lower()


def компилировать(text):
    слова = [w for w in нормализовать(text).split(' ') if w]
    карта = {}
    for i, w in enumerate(слова[:-1]):
        карта.setdefault(w, []).append(слова[i + 1])
    return '|'.join('%s=%s' % (k, ','.join(v)) for k, v in карта.items()), карта


