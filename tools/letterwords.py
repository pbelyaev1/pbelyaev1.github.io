ШИПЯЩИЕ = 'гкхжшщч'

def склонение(им, род):
    """Возвращает (винительный, родительный, дательный, предложный)."""
    if им in ИСКЛЮЧЕНИЯ:
        return ИСКЛЮЧЕНИЯ[им]
    осн, кон = им[:-1], им[-1]
    if род == 'ж':
        if кон == 'а':
            ы = 'и' if осн[-1] in ШИПЯЩИЕ else 'ы'
            return (осн + 'у', осн + ы, осн + 'е', осн + 'е')
        if кон == 'я':
            return (осн + 'ю', осн + 'и', осн + 'е', осн + 'е')
        if кон == 'ь':
            return (им, осн + 'и', осн + 'и', осн + 'и')
    if род == 'с':
        if кон == 'о':
            return (им, осн + 'а', осн + 'у', осн + 'е')
        if кон == 'е':
            return (им, осн + 'я', осн + 'ю', осн + 'е')
    # беглая гласная: песок → песка, носок → носка, листок → листка
    if род == 'м' and им.endswith('ок') and len(им) > 3:
        к = им[:-2] + 'к'
        return (им, к + 'а', к + 'у', к + 'е')
    # мужской
    if кон == 'й':
        return (им, осн + 'я', осн + 'ю', осн + 'е')
    if кон == 'ь':
        return (им, осн + 'я', осн + 'ю', осн + 'е')
    return (им, им + 'а', им + 'у', им + 'е')

